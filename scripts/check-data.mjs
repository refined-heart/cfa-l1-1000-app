import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = path.join(root, 'src', 'data', 'questions.json');
const q = JSON.parse(fs.readFileSync(p, 'utf8'));
const by = Object.groupBy(q, x => x.subject);
console.log('总题数:', q.length);
for (const [k,v] of Object.entries(by)) console.log(k, v.length, '题', new Set(v.map(x=>x.section)).size, '节');
const bad = q.filter(x => !x.stem || !x.answer || !x.options?.A || !x.options?.B || !x.options?.C);
console.log('数据不完整:', bad.length);
if (q.length !== 1000 || bad.length) process.exit(1);
