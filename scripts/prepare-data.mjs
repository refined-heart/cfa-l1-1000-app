import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src', 'data');
const parts = [1,2,3,4].map(i => path.join(dir, `questions.part${i}.b64`));
for (const p of parts) if (!fs.existsSync(p)) throw new Error(`Missing dataset part: ${p}`);
const b64 = parts.map(p => fs.readFileSync(p, 'utf8').trim()).join('');
const json = zlib.gunzipSync(Buffer.from(b64, 'base64'));
fs.writeFileSync(path.join(dir, 'questions.json'), json);
console.log(`Prepared questions.json (${json.length} bytes)`);
